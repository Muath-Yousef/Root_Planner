export const PEP_BEGIN = '# >>> EMBEDDED PEP BEGIN (SCA-002) - locked, generated by socroot-topology-studio >>>';
export const PEP_END = '# <<< EMBEDDED PEP END <<<';
export const CUSTOM_BEGIN = '            # >>> CUSTOM BEGIN';
export const CUSTOM_END = '            # <<< CUSTOM END';

/** SCA-002: the four non-droppable interceptors. Identical for every employee. */
export const PEP_BLOCK: string = [
  PEP_BEGIN,
  'async def _pep_enter(self, task, ctx):',
  '    """Runs at the start of every cycle. Do not edit."""',
  '    # 1. Kill-switch interceptor',
  '    await self.kill_switch.assert_employee_active(self.EMPLOYEE_ID)',
  '    # 2. Budget pre-reserve interceptor',
  '    await self.budget_guard.reserve(task["task_id"], self.DEPARTMENT_ID, ctx.estimated_cost_usd)',
  '',
  'def _pep_tool(self, tool_id, **kwargs):',
  '    """3. Policy validation interceptor: every tool call is enforced first."""',
  '    self.policy_engine.enforce(self.EMPLOYEE_ID, self.ROLE, f"tool:{tool_id}", kwargs)',
  '    self.local_policy.validate_tool_execution(tool_id)',
  '',
  'async def _pep_exit(self, task, ctx):',
  '    """4. Ephemerality interceptor: wipe session memory when the cycle ends."""',
  '    ctx.working_memory.wipe()',
  PEP_END,
].join('\n');
export const pepSha256 = () => sha256(PEP_BLOCK);
export const touchesPep = (code: string) => /EMBEDDED PEP|_pep_enter|_pep_tool|_pep_exit/.test(code);

const q = (v: unknown) => JSON.stringify(v);
export const contractJson = (c: EmployeeConfig) => `${JSON.stringify(c.contract, null, 2)}\n`;
export const manifestYaml = (c: EmployeeConfig) => dump(c.manifest, { lineWidth: 100, noRefs: true });

const indent = (s: string) => s.split('\n').map((l) => (l ? `    ${l}` : l)).join('\n');
function formatCustomCode(code: string): string {
  const trimmed = code.trim();
  if (!trimmed) return '            pass';
  const lines = code.replace(/\s+$/, '').split('\n');
  const nonEmpty = lines.filter((l) => l.trim().length > 0);
  const minIndent = nonEmpty.length === 0 ? 0 : Math.min(...nonEmpty.map((l) => l.match(/^ */)?.[0].length ?? 0));
  return lines.map((l) => {
    if (!l.trim()) return '';
    const rel = l.slice(minIndent);
    return `            ${rel}`;
  }).join('\n');
}

export function employeePy(c: EmployeeConfig): string {
  const ct = c.contract as { employee_id: string; role: string; department: string; runtime_config: { docker_network: string } };
  return [
    `"""${ct.employee_id} — generated by socroot-topology-studio. Contains no secrets (SEC-001)."""`,
    'from core.kernel.base_employee import BaseEmployee  # shared pinned core (SCA-001)',
    'from core.kernel.context import WorkingMemory, build_llm_context',
    'from .policies import LocalPolicyEngine',
    'from .tools import TOOLS',
    '',
    '',
    'class Employee(BaseEmployee):',
    `    EMPLOYEE_ID = ${q(ct.employee_id)}`,
    `    ROLE = ${q(ct.role)}`,
    `    DEPARTMENT_ID = ${q(ct.department)}`,
    `    NETWORK_MODE = ${q(ct.runtime_config.docker_network)}`,
    '    TOOLS = TOOLS',
    '    local_policy = LocalPolicyEngine()',
    '',
    indent(PEP_BLOCK),
    '',
    '    async def execute(self, task, ctx):',
    '        await self._pep_enter(task, ctx)',
    '        try:',
    CUSTOM_BEGIN,
    formatCustomCode(c.custom_code),
    CUSTOM_END,
    '        finally:',
    '            await self._pep_exit(task, ctx)',
    '',
  ].join('\n');
}

export function toolsPy(c: EmployeeConfig): string {
  const ct = c.contract as { employee_id: string; tools?: { tool_id: string; description: string; is_idempotent: boolean }[] };
  const tools = ct.tools ?? [];
  return [
    `"""Deterministic tools for ${ct.employee_id}. Network access exists only through SSRFGuard (§2.1.4)."""`,
    'from core.kernel.ssrf_guard import SSRFGuard',
    'from core.kernel.vault import resolve_secret_ref',
    '',
    '# SEC-001: secret references only. Real values are injected from the vault at container start.',
    'SECRET_REFS = {',
    ...c.secrets.map((s) => `    ${q(s.name)}: ${q(s.ref)},`),
    '}',
    '',
    'def secret(name: str) -> str:',
    '    """Resolve a secret by name at runtime. Input: name. Output: value. Raises KeyError for unknown names."""',
    '    return resolve_secret_ref(SECRET_REFS[name])',
    '',
    ...tools.flatMap((t) => [
      '',
      `def ${t.tool_id.replace(/[^A-Za-z0-9_]/g, '_')}(**inputs) -> dict:`,
      `    """${t.description}`,
      '',
      `    Inputs: keyword arguments. Output: dict. Idempotent: ${t.is_idempotent ? 'yes' : 'no'}.`,
      '    Raises: PolicyDenied when the local policy refuses the call.',
      '    """',
      `    return {"tool": ${q(t.tool_id)}, "status": "ok", "inputs": inputs}`,
    ]),
    '',
    'TOOLS = {',
    ...tools.map((t) => `    ${q(t.tool_id)}: ${t.tool_id.replace(/[^A-Za-z0-9_]/g, '_')},`),
    '}',
    '',
  ].join('\n');
}

export function policiesPy(c: EmployeeConfig): string {
  const ct = c.contract as { role: string; tools?: { tool_id: string }[]; runtime_config: { docker_network: string } };
  const def = getRole(ct.role);
  const none = ct.runtime_config.docker_network === 'none';
  const list = (xs: string[]) => (xs.length ? `[${xs.map(q).join(', ')}]` : '[]');
  return [
    `"""Local policies for role ${ct.role}. Default deny: anything not allowed is refused (POL_DEFAULT_DENY)."""`,
    'from core.governance.policy_engine import EgressViolationError',
    '',
    '# §4.2.1 (derived roles are marked in the studio registry)',
    `ROLE_PERMISSIONS = ${list(def?.permissions?.grants ?? [])}`,
    `ROLE_PROHIBITIONS = ${list(def?.permissions?.prohibitions ?? [])}`,
    '',
    'class LocalPolicyEngine:',
    `    ALLOWED_TOOLS = {${(ct.tools ?? []).map((t) => q(t.tool_id)).join(', ')}}`,
    '',
    '    def validate_tool_execution(self, tool_name: str) -> None:',
    '        if tool_name not in self.ALLOWED_TOOLS:',
    '            raise EgressViolationError(f"Tool {tool_name!r} is not permitted. Allowed: {self.ALLOWED_TOOLS}")',
    '',
    '    def block_outbound_network(self) -> None:',
    none
      ? '        raise EgressViolationError("POL_DRF_HARD_01: ZERO network egress. All external access is permanently blocked.")'
      : '        return None  # egress is allowed only through SSRFGuard',
    '',
  ].join('\n');
}

export interface GeneratedFile { path: string; content: string }
/** The six-file bundle of one employee (§2.1): contract.json, manifest.yaml, employee.py, tools.py, policies.py, skills/*.md. */
export function employeeFiles(c: EmployeeConfig): GeneratedFile[] {
  return [
    { path: 'contract.json', content: contractJson(c) }, { path: 'manifest.yaml', content: manifestYaml(c) },
    { path: 'employee.py', content: employeePy(c) }, { path: 'tools.py', content: toolsPy(c) }, { path: 'policies.py', content: policiesPy(c) },
    ...c.skills.map((s) => ({ path: `skills/${s.name}`, content: s.body.endsWith('\n') ? s.body : `${s.body}\n` })),
  ];
}
export const networkOf = (c: EmployeeConfig): NetworkMode => ((c.contract as { runtime_config?: { docker_network?: NetworkMode } }).runtime_config?.docker_network) ?? 'internal';
